#!/usr/bin/env python3
"""Generate the per-format icon set from the DaVinci Render Kit masters.

The kit ships one 1254x1254 RGBA master per format. The installer and the
operating-system shell need ICO files with several sizes, and the Linux packages
need PNGs in the hicolor layout. This script is deterministic: the same masters
always produce the same files, and it refuses to run when a master is missing.

Usage: python scripts/generate-filetype-icons.py
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
KIT_ICONS = ROOT.parent / "DaVinci_Render_Kit" / "png"
OUT = ROOT / "src-tauri" / "icons" / "filetypes"

# The kit keeps its generated names; map them to stable file names. The 1254 px
# PNG masters are used rather than the 256 px ICO previews in `icons/`.
MASTERS = {
    "md": "Графитовая иконка MD с красным акцентом-2.png",
    "json": "Премиум-иконка JSON с золотыми скобками-1.png",
    "csv": "Металлическая CSV-иконка с изумрудной таблицей-4.png",
    "log": "Премиальная иконка LOG с циановым акцентом-5.png",
    "xml": "Премиальная иконка XML с фиолетовой вкладкой-3.png",
}

# Every size the application and the OS shell can ask for.
PNG_SIZES = (16, 20, 24, 32, 48, 64, 128, 256, 512)
ICO_SIZES = (16, 24, 32, 48, 64, 128, 256)


def load_master(path: Path) -> Image.Image:
    """Open one kit master as a square RGBA image."""
    if not path.exists():
        raise SystemExit(f"missing master: {path}")
    image = Image.open(path)
    image.load()
    image = image.convert("RGBA")
    if image.width != image.height:
        edge = max(image.width, image.height)
        canvas = Image.new("RGBA", (edge, edge), (0, 0, 0, 0))
        canvas.paste(image, ((edge - image.width) // 2, (edge - image.height) // 2))
        image = canvas
    return image


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for kind, master_name in MASTERS.items():
        image = load_master(KIT_ICONS / master_name)
        for size in PNG_SIZES:
            resized = image.resize((size, size), Image.Resampling.LANCZOS)
            resized.save(OUT / f"davinci-{kind}-{size}.png", format="PNG", optimize=True)
        # One multi-size ICO is what Windows expects; Pillow derives every entry
        # from the 256 px version, which keeps the small sizes crisp.
        ico_source = image.resize((256, 256), Image.Resampling.LANCZOS)
        ico_source.save(OUT / f"davinci-{kind}.ico", format="ICO", sizes=[(s, s) for s in ICO_SIZES])
        print(f"{kind}: {len(PNG_SIZES)} png + ico")

    # A small manifest keeps the packaging step honest about what exists.
    manifest = OUT / "MANIFEST.txt"
    manifest.write_text(
        "Generated by scripts/generate-filetype-icons.py\n"
        + "\n".join(sorted(p.name for p in OUT.iterdir() if p.suffix in {".png", ".ico"}))
        + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
